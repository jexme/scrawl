def run(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def read_license(directory):
    for name in ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING"):
        path = os.path.join(directory, name)
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                return f.read().strip()
    sys.exit(f"no license file in {directory}")


def modules():
    """The modules that take part in the build, without the project itself: path, version, directory."""
    out = run("go", "list", "-deps", "-f",
              "{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}|{{with .Replace}}{{.Dir}}{{end}}{{end}}",
              "./cmd/scrawl")
    found = {}
    for line in out.splitlines():
        parts = line.split("|")
        if len(parts) != 4 or not parts[0] or parts[0] == MODULE:
            continue
        path, version, directory, replaced = parts
        found[path] = (version, replaced or directory)
    return found


def main():
    mods = modules()
    goroot = run("go", "env", "GOROOT")
    image_dir = mods["golang.org/x/image"][1]

    out = ["# Third-party notices", "",
           "Scrawl is distributed under the MIT License (see `LICENSE`). The binary",
           "includes the following third-party components. This file is generated by",
           "`make notices`; do not edit it by hand.", "",
           "| Component | Version | License |", "| --- | --- | --- |",
           "| Go standard library and runtime | toolchain | BSD-3-Clause |"]
    for path in sorted(mods):
        version, _ = mods[path]
        out.append(f"| `{path}` | {version} | {SPDX.get(path, 'see below')} |")
    out += ["| Go fonts (Bigelow & Holmes), via `gioui.org/font/gofont` | x/image | BSD-3-Clause |",
            "| Icon shapes from Tabler Icons | 3.x | MIT |", "",
            "Runtime library `libpipewire` (MIT) is linked dynamically and is not distributed",
            "with Scrawl.", ""]

    def section(title, text):
        out.extend([f"## {title}", "", "```text", text, "```", ""])

    section("Go standard library and runtime", read_license(goroot))
    for path in sorted(mods):
        section(path, read_license(mods[path][1]))
    with open(os.path.join(image_dir, "font", "gofont", "ttfs", "README"), encoding="utf-8") as f:
        section("Go fonts", f.read().strip())
    section("Tabler Icons", TABLER)

    with open(os.path.join(ROOT, "THIRD_PARTY_NOTICES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"THIRD_PARTY_NOTICES.md: {len(mods) + 3} components")


if __name__ == "__main__":
    main()
